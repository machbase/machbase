CREATE USER DFQ_REMOTE_LAB IDENTIFIED BY 'dfq_loopback_lab_only';

GRANT READ ON DIRECTORY '${DFQ_FILES}' TO DFQ_REMOTE_LAB;
GRANT READ ON ENDPOINT '${DFQ_HTTP}' TO DFQ_REMOTE_LAB;
GRANT READ ON ENDPOINT '${DFQ_OTHER}' TO DFQ_REMOTE_LAB;
GRANT READ ON ENDPOINT '${DFQ_S3}' PROFILE 'dfq-lab' TO DFQ_REMOTE_LAB;
GRANT READ ON ENDPOINT '${DFQ_S3}' USING ENVIRONMENT TO DFQ_REMOTE_LAB;
GRANT READ ON ENDPOINT '${DFQ_FTPS}' USING NETRC TO DFQ_REMOTE_LAB;

CREATE VIEW DFQ_REMOTE_LAB_VIEW AS
SELECT id, v
FROM READ('source=${DFQ_HTTP}/measurements.csv', 'format=csv',
          'header=true', 'type.id=LONG', 'type.v=LONG');

GRANT SELECT ON DFQ_REMOTE_LAB_VIEW TO DFQ_REMOTE_LAB;
